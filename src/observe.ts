import {Immer, Patch, Draft, isMap, isSet} from "./internal"
import {enablePatches} from "./plugins/patches"
import {enableMapSet} from "./plugins/mapset"

/**
 * A single segment of an observation path. Use strings for plain object
 * properties, numbers for array indices and the (object) key itself for
 * `Map` keys, matching the semantics of Immer patch paths.
 */
export type ObserverPathSegment = any

/** A path to an exact value or the root of a subtree. */
export type ObserverPath = readonly ObserverPathSegment[]

/** The event delivered to observation listeners. */
export interface ObservationEvent {
	/** The subscribed path (root-relative). */
	readonly path: ObserverPathSegment[]
	/** The value at `path` in the base (pre-commit) state. */
	readonly oldValue: any
	/** The value at `path` in the committed (post-commit) state. */
	readonly newValue: any
	/**
	 * The committed root state of the produce call that triggered this
	 * notification. Useful as the base for a follow-up (queued) produce.
	 */
	readonly state: any
	/**
	 * The subset of the produced patches that affects this subscription,
	 * expressed as root-relative paths exactly as generated by Immer.
	 */
	readonly patches: Patch[]
}

export type ObservationListener = (event: ObservationEvent) => void

/** The result of an observed `produce` call. */
export interface ObservedProduceResult<State> {
	/** The committed next state. Never rolled back by listener errors. */
	readonly state: State
	/** All patches generated by this produce call. */
	readonly patches: Patch[]
	/** The inverse patches generated by this produce call. */
	readonly inversePatches: Patch[]
	/**
	 * Errors thrown by notification listeners, aggregated in notification
	 * order. For re-entrant (queued) produce calls this array is populated
	 * once the enclosing notification round has fully drained.
	 */
	readonly errors: unknown[]
}

export interface ProduceObserver {
	/**
	 * Runs `recipe` through `produceWithPatches`, commits the resulting
	 * state and only then notifies the affected subscribers, in registration
	 * order. When called from inside a notification, the recipe still runs
	 * immediately, but its notifications are queued and dispatched after the
	 * current notification round has finished (FIFO, never recursively).
	 */
	produce<Base>(
		base: Base,
		recipe: (draft: Draft<Base>) => void | Base | undefined
	): ObservedProduceResult<Base>
	/**
	 * Subscribes `listener` to an exact path or subtree. Returns an
	 * unsubscribe function. Unsubscribing (and subscribing) while a
	 * notification round is in progress takes effect only after that round
	 * has ended.
	 */
	subscribe(path: ObserverPath, listener: ObservationListener): () => void
	/** The number of currently active subscriptions. */
	readonly size: number
}

interface Subscription {
	path: ObserverPathSegment[]
	listener: ObservationListener
	removed: boolean
}

interface NotificationJob {
	base: any
	next: any
	patches: Patch[]
	errors: unknown[]
}

function segmentsEqual(
	a: ObserverPathSegment,
	b: ObserverPathSegment
): boolean {
	if (a === b) return true
	// Array indices arrive as numbers in patches, but subscribers may use
	// the string form ("0"). Map keys and other objects only match by
	// identity, per real patch semantics.
	const ta = typeof a
	const tb = typeof b
	if (
		(ta === "string" || ta === "number") &&
		(tb === "string" || tb === "number")
	) {
		return String(a) === String(b)
	}
	return false
}

function isPrefixOf(prefix: ObserverPath, path: ObserverPath): boolean {
	if (prefix.length > path.length) return false
	for (let i = 0; i < prefix.length; i++) {
		if (!segmentsEqual(prefix[i], path[i])) return false
	}
	return true
}

/** A subscription is affected when its path and a patch path overlap. */
function pathsIntersect(
	subscriptionPath: ObserverPath,
	patchPath: ObserverPath
): boolean {
	return (
		isPrefixOf(subscriptionPath, patchPath) ||
		isPrefixOf(patchPath, subscriptionPath)
	)
}

function getValueAtPath(root: any, path: ObserverPath): any {
	let value = root
	for (const segment of path) {
		if (value === undefined || value === null) return undefined
		if (isMap(value)) {
			value = value.get(segment)
		} else if (isSet(value)) {
			value = value.has(segment) ? segment : undefined
		} else {
			value = value[segment]
		}
	}
	return value
}

/**
 * Creates a reusable observation adapter around `produce`. Subscribers
 * register for exact paths or subtrees and are notified after a successful
 * produce commit, but only when the generated patches actually affect their
 * path. The `Patches` and `MapSet` plugins are enabled automatically.
 *
 * @param immerInstance optional `Immer` instance to wrap; a dedicated
 * instance is created when omitted.
 */
export function createProduceObserver(immerInstance?: Immer): ProduceObserver {
	enablePatches()
	enableMapSet()
	const immer = immerInstance ?? new Immer()

	let subscriptions: Subscription[] = []
	let dispatching = false
	const queue: NotificationJob[] = []

	function notify(job: NotificationJob) {
		// No actual change -> no notifications at all.
		if (job.patches.length === 0) return
		// Snapshot so listeners (un)subscribing during this round do not
		// alter the current round's delivery.
		const current = subscriptions.filter(sub => !sub.removed)
		for (const sub of current) {
			const relevant = job.patches.filter(patch =>
				pathsIntersect(sub.path, patch.path)
			)
			if (relevant.length === 0) continue
			const event: ObservationEvent = {
				path: sub.path.slice(),
				oldValue: getValueAtPath(job.base, sub.path),
				newValue: getValueAtPath(job.next, sub.path),
				state: job.next,
				patches: relevant
			}
			try {
				sub.listener(event)
			} catch (error) {
				// Listener errors are aggregated, never rethrown into the
				// commit, and never prevent other listeners from running.
				job.errors.push(error)
			}
		}
	}

	function drain(job: NotificationJob) {
		dispatching = true
		try {
			notify(job)
			// Re-entrant produce calls enqueue here; drain strictly in FIFO
			// order so notification order is never disturbed by recursion.
			while (queue.length > 0) {
				notify(queue.shift()!)
			}
		} finally {
			dispatching = false
			// Unsubscriptions take effect only after the round has ended.
			if (subscriptions.some(sub => sub.removed)) {
				subscriptions = subscriptions.filter(sub => !sub.removed)
			}
		}
	}

	const observer: ProduceObserver = {
		produce<Base>(
			base: Base,
			recipe: (draft: Draft<Base>) => void | Base | undefined
		): ObservedProduceResult<Base> {
			const [state, patches, inversePatches] = immer.produceWithPatches(
				base,
				recipe as any
			)
			const errors: unknown[] = []
			const job: NotificationJob = {base, next: state, patches, errors}
			if (dispatching) {
				// Initiated from inside a notification: queue the notifications
				// until the current round ends. The (shared) errors array is
				// filled once the queue drains.
				queue.push(job)
			} else {
				drain(job)
			}
			return {state, patches, inversePatches, errors}
		},
		subscribe(path: ObserverPath, listener: ObservationListener) {
			const sub: Subscription = {
				path: path.slice(),
				listener,
				removed: false
			}
			subscriptions.push(sub)
			return () => {
				if (sub.removed) return
				sub.removed = true
				if (!dispatching) {
					subscriptions = subscriptions.filter(s => s !== sub)
				}
			}
		},
		get size() {
			return subscriptions.filter(sub => !sub.removed).length
		}
	}
	return observer
}
