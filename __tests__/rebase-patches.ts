// @ts-nocheck
"use strict"
import {describe, expect, it} from "vitest"
import {
	applyPatches,
	produceWithPatches,
	rebasePatches,
	enablePatches,
	freeze
} from "../src/immer"

enablePatches()

function rebaseCheck(base, localPatches, incomingPatches) {
	const result = rebasePatches(base, localPatches, incomingPatches)
	const localState = applyPatches(base, localPatches)
	if (result.conflicts.length === 0) {
		const merged = applyPatches(localState, result.patches)
		const restored = applyPatches(merged, result.inversePatches)
		expect(restored).toEqual(localState)
	}
	return {result, localState}
}

describe("rebasePatches", () => {
	it("acceptance: delete A locally, replace original B incoming shifts to index 0 and keeps C", () => {
		const base = {items: ["A", "B", "C"]}
		const localPatches = [{op: "remove", path: ["items", 0]}]
		const incomingPatches = [{op: "replace", path: ["items", 1], value: "B2"}]
		const {result} = rebaseCheck(base, localPatches, incomingPatches)
		expect(result.patches).toEqual([
			{op: "replace", path: ["items", 0], value: "B2"}
		])
		expect(
			applyPatches(applyPatches(base, localPatches), result.patches)
		).toEqual({
			items: ["B2", "C"]
		})
		expect(result.conflicts).toEqual([])
	})

	it("acceptance: insertions at the same base gap keep local elements first", () => {
		const base = {items: [1, 2]}
		const localPatches = [{op: "add", path: ["items", 1], value: "L"}]
		const incomingPatches = [{op: "add", path: ["items", 1], value: "I"}]
		const {result} = rebaseCheck(base, localPatches, incomingPatches)
		expect(result.patches).toEqual([
			{op: "add", path: ["items", 2], value: "I"}
		])
		expect(
			applyPatches(applyPatches(base, localPatches), result.patches)
		).toEqual({items: [1, "L", "I", 2]})
	})

	it("acceptance: local delete of original B vs incoming modify of original B conflicts", () => {
		const base = {items: ["A", "B", "C"]}
		const localPatches = [{op: "remove", path: ["items", 1]}]
		const incomingPatches = [{op: "replace", path: ["items", 1], value: "B2"}]
		const result = rebasePatches(base, localPatches, incomingPatches)
		expect(result.patches).toEqual([])
		expect(result.inversePatches).toEqual([])
		expect(result.conflicts).toMatchObject([
			{localIndex: 0, incomingIndex: 0, path: ["items", 1]}
		])
	})

	it("nested arrays and repeated index shifts", () => {
		const base = {
			items: ["A", "B", "C", {nested: ["x", "y", "z"]}],
			tail: [{v: 1}, {v: 2}]
		}
		// local: remove original A, then original C (index shifts twice),
		// then delete original x from the last object nested array
		const localPatches = [
			{op: "remove", path: ["items", 0]},
			{op: "remove", path: ["items", 1]},
			{op: "remove", path: ["items", 1, "nested", 0]}
		]
		// incoming: replace original B, replace original z, touch tail
		// original element 1; indices follow original elements
		const incomingPatches = [
			{op: "replace", path: ["items", 1], value: "B2"},
			{op: "replace", path: ["items", 3, "nested", 2], value: "z2"},
			{op: "replace", path: ["tail", 1, "v"], value: 20}
		]
		const {result} = rebaseCheck(base, localPatches, incomingPatches)
		expect(result.patches).toEqual([
			{op: "replace", path: ["items", 0], value: "B2"},
			{op: "replace", path: ["items", 1, "nested", 1], value: "z2"},
			{op: "replace", path: ["tail", 1, "v"], value: 20}
		])
		expect(
			applyPatches(applyPatches(base, localPatches), result.patches)
		).toEqual({
			items: ["B2", {nested: ["y", "z2"]}],
			tail: [{v: 1}, {v: 20}]
		})
	})

	it("object keys containing slashes are just path segments", () => {
		const base = {"a/b": {"c/d": 1}, other: 2}
		const localPatches = [{op: "replace", path: ["other"], value: 22}]
		const incomingPatches = [{op: "replace", path: ["a/b", "c/d"], value: 11}]
		const {result} = rebaseCheck(base, localPatches, incomingPatches)
		expect(result.patches).toEqual(incomingPatches)
	})

	it("same-value replacements are treated as duplicates", () => {
		const base = {a: {x: 1}}
		const patch = {op: "replace", path: ["a"], value: {x: 1}}
		const {result} = rebaseCheck(
			base,
			[patch],
			[JSON.parse(JSON.stringify(patch))]
		)
		expect(result.patches).toEqual([])
		expect(result.conflicts).toEqual([])
	})

	it("works with frozen base and patches generated by produceWithPatches", () => {
		const base = freeze({items: ["A", "B", "C"], meta: {ok: true}})

		// Identity-preserving remove/add patches (the operation model
		// rebasePatches understands) against a frozen base; object-level
		// patches are generated by produceWithPatches.
		const [, localPatches] = produceWithPatches(base, draft => {
			draft.meta.ok = false
		})
		localPatches.unshift({op: "remove", path: ["items", 0]})
		const [, incomingPatches] = produceWithPatches(base, draft => {
			draft.meta.tag = "incoming"
		})
		incomingPatches.unshift({
			op: "replace",
			path: ["items", 1],
			value: "B2"
		})
		const result = rebasePatches(base, localPatches, incomingPatches)
		expect(result.conflicts).toEqual([])
		const localState = applyPatches(base, localPatches)
		const merged = applyPatches(localState, result.patches)
		expect(merged).toEqual({
			items: ["B2", "C"],
			meta: {ok: false, tag: "incoming"}
		})
		expect(applyPatches(merged, result.inversePatches)).toEqual(localState)
		expect(base).toEqual({items: ["A", "B", "C"], meta: {ok: true}})
	})

	it("different object properties merge independently", () => {
		const base = {a: 1, b: 2, nested: {x: 1, y: 2}}
		const localPatches = [{op: "replace", path: ["a"], value: 10}]
		const incomingPatches = [
			{op: "replace", path: ["b"], value: 20},
			{op: "replace", path: ["nested", "y"], value: 22}
		]
		const {result} = rebaseCheck(base, localPatches, incomingPatches)
		expect(result.patches).toEqual(incomingPatches)
	})

	it("delete vs modify, ancestor replace vs descendant modify", () => {
		const base = {a: {x: 1}, b: {y: 2}, items: [{k: 1}, {k: 2}]}
		const localPatches = [
			{op: "remove", path: ["a"]},
			{op: "replace", path: ["b"], value: {z: 9}},
			{op: "replace", path: ["items", 0], value: {k: 9}}
		]
		const incomingPatches = [
			{op: "replace", path: ["a", "x"], value: 11},
			{op: "replace", path: ["b", "y"], value: 22},
			{op: "replace", path: ["items", 0, "k"], value: 11}
		]
		const result = rebasePatches(base, localPatches, incomingPatches)
		expect(result.patches).toEqual([])
		expect(result.conflicts.map(c => c.reason).sort()).toEqual([
			"delete-ancestor-vs-modify-descendant",
			"replace-ancestor-vs-modify-descendant",
			"replace-ancestor-vs-modify-descendant"
		])
	})

	it("rejects Map/Set patches explicitly", () => {
		const base = {m: new Map(), s: new Set()}
		expect(() =>
			rebasePatches(base, [], [{op: "remove", path: ["m", "a"]}])
		).toThrow(/Map\/Set/)
		expect(() =>
			rebasePatches({a: 1}, [], [{op: "add", path: ["x"], value: new Map()}])
		).toThrow(/Map\/Set/)
	})

	it("never mutates base or input patch arrays", () => {
		const base = {items: ["A", "B"], a: {x: 1}}
		const localPatches = [
			{op: "add", path: ["items", 1], value: {deep: [1, 2]}}
		]
		const incomingPatches = [
			{op: "add", path: ["items", 1], value: {deep: [3, 4]}}
		]
		const baseSnapshot = JSON.parse(JSON.stringify(base))
		const localSnapshot = JSON.parse(JSON.stringify(localPatches))
		const incomingSnapshot = JSON.parse(JSON.stringify(incomingPatches))
		rebaseCheck(base, localPatches, incomingPatches)
		expect(base).toEqual(baseSnapshot)
		expect(localPatches).toEqual(localSnapshot)
		expect(incomingPatches).toEqual(incomingSnapshot)
	})

	it("frozen input patch arrays stay untouched and still rebase", () => {
		const base = {items: ["A", "B"]}
		const local = Object.freeze([
			Object.freeze({op: "add", path: Object.freeze(["items", 1]), value: "L"})
		])
		const incoming = Object.freeze([
			Object.freeze({op: "add", path: Object.freeze(["items", 1]), value: "I"})
		])
		const {result} = rebaseCheck(base, local, incoming)
		expect(result.patches).toEqual([
			{op: "add", path: ["items", 2], value: "I"}
		])
	})

	it("demo: prints inputs, rebased patches and conflict indices", () => {
		const scenarios = [
			{
				name: "local deletes A; incoming replaces original B",
				base: {items: ["A", "B", "C"]},
				local: [{op: "remove", path: ["items", 0]}],
				incoming: [{op: "replace", path: ["items", 1], value: "B2"}]
			},
			{
				name: "same-gap insertion ordering (local first)",
				base: {items: [1, 2]},
				local: [{op: "add", path: ["items", 1], value: "L"}],
				incoming: [{op: "add", path: ["items", 1], value: "I"}]
			},
			{
				name: "conflict: delete original B vs modify original B",
				base: {items: ["A", "B", "C"]},
				local: [{op: "remove", path: ["items", 1]}],
				incoming: [{op: "replace", path: ["items", 1], value: "B2"}]
			}
		]
		const started = Date.now()
		for (const s of scenarios) {
			const result = rebasePatches(s.base, s.local, s.incoming)
			console.log("\n--- " + s.name)
			console.log("input base      :", JSON.stringify(s.base))
			console.log("local patches   :", JSON.stringify(s.local))
			console.log("incoming patches:", JSON.stringify(s.incoming))
			console.log("rebased patches :", JSON.stringify(result.patches))
			console.log("inverse patches :", JSON.stringify(result.inversePatches))
			console.log(
				"conflict indices:",
				JSON.stringify(
					result.conflicts.map(c => ({
						localIndex: c.localIndex,
						incomingIndex: c.incomingIndex,
						path: c.path
					}))
				)
			)
		}
		expect(Date.now() - started).toBeLessThan(90000)
	})
	it("mixed local/incoming deletes, replaces and inserts at several gaps", () => {
		const base = {items: [0, 1, 2, 3]}
		const localPatches = [
			{op: "remove", path: ["items", 0]},
			{op: "add", path: ["items", 0], value: "L"}
		]
		const incomingPatches = [
			{op: "remove", path: ["items", 2]},
			{op: "replace", path: ["items", 1], value: "X"},
			{op: "add", path: ["items", 0], value: "I"},
			{op: "add", path: ["items", 0], value: "I2"}
		]
		const {result} = rebaseCheck(base, localPatches, incomingPatches)
		expect(result.patches).toEqual([
			{op: "remove", path: ["items", 2]},
			{op: "replace", path: ["items", 1], value: "X"},
			{op: "add", path: ["items", 2], value: "I"},
			{op: "add", path: ["items", 2], value: "I2"}
		])
		expect(
			applyPatches(applyPatches(base, localPatches), result.patches)
		).toEqual({items: ["L", "X", "I2", "I", 3]})
	})

	it("local replace whole subtree then modify inside conflicts with incoming duplicate replacement", () => {
		const base = {a: {x: 1}}
		const localPatches = [
			{op: "replace", path: ["a"], value: {x: 1}},
			{op: "replace", path: ["a", "x"], value: 11}
		]
		const incomingPatches = [{op: "replace", path: ["a"], value: {x: 1}}]
		const result = rebasePatches(base, localPatches, incomingPatches)
		expect(result.patches).toEqual([])
		expect(result.conflicts).toMatchObject([{reason: "replace-vs-replace"}])
	})
})
